"""Hand-build an artificial filter model, save it, and score its AAD loss.

The inverse of the training scripts: instead of learning the 20+20 conv filters by
gradient descent, you type their weights by hand below, the script saves the resulting
"artificial" model, then runs it (no training, no gradients) on a number of freshly
generated *realistic* synthetic matrices and reports the average AAD loss.

"AAD loss" here is the full training objective from
custom_synthetic_train_absolute_deviation.py: the normalized cross-species mean
absolute deviation (computed on the SMOOTH_SIGMA-smoothed SR profile) plus the L1
activation-sparsity penalty. Each realistic matrix is generated by the same
make_synthetic_matrix used by custom_synthetic_train_realistic.py, so the matrices
match what that training script sees; successive matrices differ because each draws
fresh randomness from the (seeded) global RNG.
"""

import json
import logging
import math
import os
import sys

import torch

# custom_model.py / custom_synthetic_train_realistic.py live in the parent dir
# (custom_model/); add it to sys.path so this script imports cleanly no matter which
# directory it's run from. Mirrors imperfect_train.py.
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import torch.nn.functional as F

from custom_model import PNASModel
from custom_synthetic_train_realistic import (
    L1_LAMBDA,
    MOTIFS,
    N_SPECIES,
    NUCLEOTIDES,
    NUM_BLOCKS,
    SEQ_LEN,
    SMOOTH_SIGMA,
    make_synthetic_matrix,
)

logging.basicConfig(level=logging.INFO, format="%(message)s")
logger = logging.getLogger(__name__)

# ── Evaluation setup ────────────────────────────────────────────────────────
NUM_MATRICES = 100  # number of realistic matrices to average the AAD loss over
SEED = 0  # base seed; successive matrices draw fresh randomness from here

# ── Manual filter weights ───────────────────────────────────────────────────
# Type the weights of the artificial model here. The model has two filter banks —
# conv_incl (inclusion) and conv_skip (skipping) — each with 20 filters indexed 0..19.
# A single filter is a 4x6 weight matrix plus a scalar bias:
#   - rows  = nucleotide channels in ACGT order (row 0=A, 1=C, 2=G, 3=T)
#   - cols  = the 6 kernel positions (0..5) of the sliding window
# Any filter index you leave OUT of these dicts defaults to an all-zero 4x6 weight
# and 0.0 bias, so the artificial model is fully determined by exactly what you type.
#
# Example below: conv_incl filter 0 is a poly-A detector (+1 on the A row across all 6
# positions, bias -3 so it only fires on a run of A's), matching the "AAAAAA" motif the
# realistic matrices plant. Add / edit entries to design the model you want.
CONV_INCL_WEIGHTS = {
    0: {
        "weight": [
            [+2.3523, +1.8953, +2.1077, +2.3057, -10.5182, +2.1813],  # A
            [-11.9693, -12.4442, -12.2715, -12.1691, -11.1396, -12.1416],  # C
            [-11.9670, -12.4396, -12.4443, -12.0899, -10.9838, -12.2400],  # G
            [-11.5977, -12.5383, -12.4761, -11.8209, +3.4013, -11.8807],  # T
        ],
        "bias": -6.7189,
    },
    1: {
        "weight": [
            [-11.9693, -12.4442, -12.4443, -12.0899, -10.5182, -12.1416],  # A
            [+2.3523, +1.8953, -12.2715, -12.1691, +3.4013, +2.1813],  # C
            [-11.9670, -12.4396, +2.1077, +2.3057, -10.9838, -12.2400],  # G
            [-11.5977, -12.5383, -12.4761, -11.8209, -11.1396, -11.8807],  # T
        ],
        "bias": -6.7189,
    },
}
CONV_SKIP_WEIGHTS = {}


def apply_manual_weights(conv, spec):
    """Set a conv filter bank's weights/biases in place from a spec dict.

    The bank is first fully zeroed, then each ``index -> {"weight": 4x6, "bias": f}``
    entry overwrites that filter. Indices absent from ``spec`` stay all-zero.

    Args:
        conv: An ``nn.Conv1d`` bank (``model.conv_incl`` or ``model.conv_skip``).
        spec: Mapping of filter index to ``{"weight": <4x6 nested list>, "bias": float}``.
    """
    with torch.no_grad():
        conv.weight.zero_()
        conv.bias.zero_()
        for i, s in spec.items():
            w = torch.tensor(
                s["weight"], dtype=conv.weight.dtype, device=conv.weight.device
            )
            if tuple(w.shape) != (4, 6):
                raise ValueError(
                    f"filter {i}: weight must be shape (4, 6) [ACGT x 6 positions], "
                    f"got {tuple(w.shape)}"
                )
            conv.weight[i] = w
            conv.bias[i] = float(s.get("bias", 0.0))


def main():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ── Build the artificial model by hand ──
    model = PNASModel().to(device)
    apply_manual_weights(model.conv_incl, CONV_INCL_WEIGHTS)
    apply_manual_weights(model.conv_skip, CONV_SKIP_WEIGHTS)
    model.eval()
    logger.info(
        f"Built artificial model — {len(CONV_INCL_WEIGHTS)} conv_incl and "
        f"{len(CONV_SKIP_WEIGHTS)} conv_skip filters set by hand (rest zeroed)."
    )

    # ── Save the artificial model's weights ──
    # Checkpoint format matches the training scripts (weights nested under
    # "model_state_dict") so it can be reloaded by plot_filters.py / load_partial_state_dict.
    weights_dir = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "weights"
    )
    os.makedirs(weights_dir, exist_ok=True)
    weights_path = os.path.join(weights_dir, "artificial_model_2motifs.pt")
    torch.save(
        {
            "model_state_dict": model.state_dict(),
            "metadata": {
                "dataset": "synthetic_realistic",
                "script": os.path.basename(__file__),
                "conv_incl_weights": CONV_INCL_WEIGHTS,
                "conv_skip_weights": CONV_SKIP_WEIGHTS,
                "hparams": {
                    "n_species": N_SPECIES,
                    "seq_len": SEQ_LEN,
                    "motifs": MOTIFS,
                    "num_blocks": NUM_BLOCKS,
                    "smooth_sigma": SMOOTH_SIGMA,
                    "l1_lambda": L1_LAMBDA,
                    "num_matrices": NUM_MATRICES,
                    "seed": SEED,
                },
            },
        },
        weights_path,
    )
    logger.info(f"Saved artificial model to {weights_path}")

    # ── Fixed Gaussian smoothing kernel (same construction as the AAD trainer) ──
    # Sum-normalized weighted average over position; applied with reflect padding so the
    # conserved block at position 0 isn't damped by zero edges. No learnable parameters.
    if SMOOTH_SIGMA:
        smooth_radius = math.ceil(3 * SMOOTH_SIGMA)  # kernel half-width (~3 sigma)
        offsets = torch.arange(
            -smooth_radius, smooth_radius + 1, device=device, dtype=torch.float32
        )
        gauss_kernel = torch.exp(-(offsets**2) / (2 * SMOOTH_SIGMA**2))
        gauss_kernel = (gauss_kernel / gauss_kernel.sum()).view(1, 1, -1)  # (1, 1, K)

    # ── Run the model (no gradient descent) on NUM_MATRICES realistic matrices ──
    torch.manual_seed(SEED)
    per_matrix = []  # list of dicts: sd_loss, l1, aad per matrix
    with torch.no_grad():
        for m in range(1, NUM_MATRICES + 1):
            x = make_synthetic_matrix(
                N_SPECIES, SEQ_LEN, MOTIFS, NUM_BLOCKS, device
            )  # (10, 4, 5000)

            # a_incl / a_skip are the raw (unsmoothed) summed softplus activations,
            # both (10, num_windows) and >= 0; used by the activation L1 penalty.
            sr, a_incl, a_skip = model.compute_sr_profile(x, return_activations=True)

            # Gaussian-smooth each row's SR track along position (independent per row),
            # matching the AAD training loop.
            if SMOOTH_SIGMA:
                sr = F.conv1d(
                    F.pad(
                        sr.unsqueeze(1), (smooth_radius, smooth_radius), mode="reflect"
                    ),
                    gauss_kernel,
                ).squeeze(1)

            # Numerator: cross-species mean absolute deviation per column.
            col_std = (sr - sr.mean(dim=0, keepdim=True)).abs().mean(dim=0)
            # Denominator: within-species mean absolute deviation, averaged over rows.
            within_species_scale = (
                (sr - sr.mean(dim=1, keepdim=True)).abs().mean(dim=1).mean()
            )
            if within_species_scale.item() < 1e-8:
                logger.warning(
                    f"matrix {m:3d} | within-species scale ~0 "
                    f"({within_species_scale.item():.2e}) — SR profile is flat, so the "
                    f"normalized AAD is ill-defined (NaN/inf). Set some filters so the "
                    f"model produces a non-constant SR profile."
                )

            # numerator = mean cross-species abs-dev over columns; denominator =
            # within-species scale. sd_loss is their ratio.
            numerator = col_std.mean()
            denominator = within_species_scale
            sd_loss = numerator / denominator
            l1_penalty = L1_LAMBDA * (a_incl + a_skip).mean()
            aad = sd_loss + l1_penalty

            per_matrix.append(
                {
                    "numerator": float(numerator.item()),
                    "denominator": float(denominator.item()),
                    "sd_loss": float(sd_loss.item()),
                    "l1": float(l1_penalty.item()),
                    "aad": float(aad.item()),
                }
            )
            logger.info(
                f"matrix {m:3d} | numerator = {numerator.item():.6f} "
                f"| denominator = {denominator.item():.6f} "
                f"| sd loss = {sd_loss.item():.6f} "
                f"| l1 = {l1_penalty.item():.6f} | aad = {aad.item():.6f}"
            )

    # ── Average the AAD loss over the matrices and record it ──
    avg_num = sum(d["numerator"] for d in per_matrix) / len(per_matrix)
    avg_den = sum(d["denominator"] for d in per_matrix) / len(per_matrix)
    avg_aad = sum(d["aad"] for d in per_matrix) / len(per_matrix)
    avg_sd = sum(d["sd_loss"] for d in per_matrix) / len(per_matrix)
    avg_l1 = sum(d["l1"] for d in per_matrix) / len(per_matrix)
    logger.info(
        f"Average over {NUM_MATRICES} matrices | "
        f"numerator = {avg_num:.6f} | denominator = {avg_den:.6f} | "
        f"sd loss = {avg_sd:.6f} | l1 = {avg_l1:.6f} | AAD loss = {avg_aad:.6f}"
    )

    results_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "artificial_model_aad_results_2motifs.json",
    )
    with open(results_path, "w") as f:
        json.dump(
            {
                "num_matrices": NUM_MATRICES,
                "seed": SEED,
                "avg_numerator": avg_num,
                "avg_denominator": avg_den,
                "avg_aad": avg_aad,
                "avg_sd_loss": avg_sd,
                "avg_l1": avg_l1,
                "per_matrix": per_matrix,
                "weights_path": weights_path,
            },
            f,
            indent=2,
        )
    logger.info(f"Wrote AAD results to {results_path}")
    logger.info("Done.")


if __name__ == "__main__":
    main()
